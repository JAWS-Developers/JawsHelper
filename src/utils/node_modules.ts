import ora from 'ora';
import chalk from 'chalk';
import { exec } from 'child_process';
import { promisify } from 'util';
import depcheck from 'depcheck';
import Table from 'cli-table3';
const execPromise = promisify(exec);

const options = {
    ignoreDirs: ["dist", "build", "node_modules"],
    ignoreMatches: ["@types/*"],
};

export const verifyNodeModules = async () => {
    const spinner = ora(chalk.yellow('Verifying node_modules...')).start();
    try {
        const result = await execPromise('npm ls --all --json');
        const parsedResult = JSON.parse(result.stdout);
        const hasErrors = parsedResult.problems && parsedResult.problems.length > 0;

        if (hasErrors) {
            spinner.fail(chalk.red('Issues found in node_modules:'));
            parsedResult.problems.forEach((problem: string) => {
                console.log(chalk.red(`- ${problem}`));
            });
        } else {
            spinner.succeed(chalk.green('node_modules verified successfully. No issues found.'));
            spinner.start(chalk.yellow('Running depcheck for deeper analysis...'));
            depcheck(process.cwd(), options)
                .then((result) => {
                    spinner.succeed('Depcheck completed!');

                    const table = new Table({
                        head: ['Type', 'Dependency'],
                        colWidths: [20, 50],
                        wordWrap: true,
                    });

                    result.dependencies.forEach((dep) => table.push(['Unused', dep]));
                    result.devDependencies.forEach((dep) => table.push(['Unused Dev', dep]));
                    Object.keys(result.missing).forEach((dep) =>
                        table.push(['Missing', `${dep} (used in ${result.missing[dep].join(', ')})`])
                    );
                    spinner.succeed(chalk.green('Depcheck results:'));

                    console.log(table.toString());
                })
                .catch((err) => {
                    spinner.fail('Depcheck failed!');
                    spinner.stop();
                    console.error(err);
                });
        }
    } catch (error) {
        spinner.fail(chalk.red('Failed to verify node_modules.'));
        console.error(error);
    }
};
